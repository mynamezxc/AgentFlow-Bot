import assert from 'node:assert/strict';
import {formatMessage,ownerVisible,agentAvatar,faceFor,agentGroup} from '../dist/identity.js';
const agents=[{id:'a-lead',name:'Atlas',color:'purple'},{id:'a-b',name:'ABC',face:'cat',color:'mint'}];
const html=formatMessage('Atlas: @{a-b} xin quyền C:/demo. ABC tiếp tục. <script>bad()</script>',agents);
assert.equal((html.match(/data-id="a-b"/g)||[]).length,2);
assert.ok(html.includes('agent-mention mint'));
assert.ok(!html.includes('<script>'));
assert.ok(html.includes('&lt;script&gt;'));
assert.ok(!formatMessage('xABCy `ABC` ```\nABC\n```',agents).includes('agent-mention'));
assert.ok(formatMessage('**ABC**',agents).includes('<strong><button'));
assert.ok(!formatMessage('@{unknown}',agents).includes('data-action'));
assert.ok(formatMessage('ABC.md',agents,[{id:'artifact','path':'ABC.md'}]).includes('co-artifact'));
assert.equal(ownerVisible({kind:'peer'}),false);
assert.equal(ownerVisible({kind:'handoff'}),false);
assert.equal(ownerVisible({kind:'chat',run_id:'peer'},[{id:'peer',kind:'peer'}]),false);
assert.equal(ownerVisible({kind:'chat',audience:'owner'}),true);
assert.equal(ownerVisible({kind:'chat',audience:'internal'}),false);
assert.equal(ownerVisible({kind:'progress',audience:'activity'}),true);   // renders only inside the collapsed work log
assert.equal(ownerVisible({kind:'action',audience:'activity'}),true);
assert.equal(ownerVisible({kind:'peer_reply',audience:'internal'}),false);
assert.equal(faceFor('a-lead'),'smile');
assert.ok(agentAvatar({id:'a-b',face:'<script>',color:'bad class'}).includes('purple'));
assert.ok(formatMessage('Iris xin quyền',[{id:'iris',name:'Iris - Designer'}]).includes('data-id="iris"'));
assert.ok(!formatMessage('Iris xin quyền',[{id:'i1',name:'Iris - Designer'},{id:'i2',name:'Iris - Writer'}]).includes('co-room'));
console.log('Chat rendering: 17 assertions passed');
assert.ok(agentGroup({category:'custom_department'}).includes('Custom Department'));
assert.ok(!agentGroup({category:'<script>alert(1)</script>'}).includes('<script>'));
console.log('2 custom specialty label assertions passed');
