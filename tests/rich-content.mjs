import assert from 'node:assert/strict';
import {renderMarkdown,normalizeChart,fileReference} from '../dist/rich-content.js';
const context={agents:[{id:'a-lead',name:'Atlas'}],artifacts:[{id:'a1',path:'report.md',title:'Report'},{id:'a2',path:'media/shot.png',title:'Screenshot',is_image:true}],attachments:[{id:'u1',name:'data.txt'}]};
let html=renderMarkdown('| Agent | Work |\n| --- | --- |\n| Atlas | **Ready** |',context);
assert.ok(html.includes('<table'));assert.ok(html.includes('scope="col"'));assert.ok(html.includes('co-room'));assert.ok(html.includes('<strong>Ready</strong>'));
assert.ok(!renderMarkdown('```html\n<script>alert(1)</script>\n```',context).includes('<script>'));
assert.ok(!renderMarkdown('[x](javascript:alert(1))',context).includes('href='));
assert.ok(renderMarkdown('[Report](report.md)',context).includes('rich-file-card'));
assert.ok(renderMarkdown('![Proof](media/shot.png)',context).includes('/api/outputs/a2/raw'));
assert.ok(!renderMarkdown('![bad](https://evil.example/track)',context).includes('<img'));
assert.equal(fileReference('attachment:u1',[],context.attachments).source,'attachment');
assert.equal(fileReference('../not-real.md',context.artifacts),null);
const chart={type:'bar',title:'Results <script>',data:{labels:['A','B'],datasets:[{label:'Count',data:[2,-3]}]}};
html=renderMarkdown('```chart\n'+JSON.stringify(chart)+'\n```');assert.ok(html.includes('rich-chart'));assert.ok(html.includes('chart-data'));assert.ok(!html.includes('<script>'));
assert.throws(()=>normalizeChart({...chart,type:'pie'}));
assert.throws(()=>normalizeChart({...chart,data:{labels:['A'],datasets:[{data:[Infinity]}]}}));
assert.throws(()=>normalizeChart({...chart,data:{labels:['A'],datasets:[{data:[1,2]}]}}));
assert.ok(renderMarkdown('```chart\n{"type":"oops"}\n```').includes('rich-invalid'));
assert.ok(renderMarkdown('```images\n["media/shot.png"]\n```',context).includes('rich-gallery'));
assert.ok(renderMarkdown('```files\n["report.md","absent.txt"]\n```',context).includes('File unavailable'));
assert.equal(fileReference('<report.md>',context.artifacts).record.id,'a1');
console.log('Rich content: 21 assertions passed');
// Thumbnails: <=4 images show all; >4 show 3 + a "+N" tile, remaining tiles stay hidden for the lightbox.
import {galleryTiles,imageCard,galleryMarkup} from '../dist/rich-content.js';
const many={artifacts:Array.from({length:9},(_,i)=>({id:'i'+i,path:'media/s'+i+'.png',title:'Shot '+i,is_image:true}))};
const gallery=renderMarkdown('```images\n'+JSON.stringify(many.artifacts.map(a=>a.path))+'\n```',many);
assert.equal((gallery.match(/<button type="button" class="rich-image/g)||[]).length,9);
assert.equal((gallery.match(/<button[^>]* hidden /g)||[]).length,5);
assert.ok(gallery.includes('<span class="rich-more" aria-hidden="true">+6</span>'));
assert.equal((gallery.match(/rich-more/g)||[]).length,1);
assert.ok(gallery.includes('data-lightbox-group'));assert.ok(gallery.includes('data-lightbox-src="/api/outputs/i0/raw"'));
assert.ok(gallery.includes('data-lightbox-title="Shot 0"'));
const four=renderMarkdown('```images\n'+JSON.stringify(many.artifacts.slice(0,4).map(a=>a.path))+'\n```',many);
assert.ok(!four.includes('rich-more'));assert.ok(!four.includes(' hidden '));
const five=renderMarkdown('```images\n'+JSON.stringify(many.artifacts.slice(0,5).map(a=>a.path))+'\n```',many);
assert.ok(five.includes('+2</span>'));
assert.deepEqual(galleryTiles(4,3),{});assert.deepEqual(galleryTiles(5,3),{more:2});assert.deepEqual(galleryTiles(5,4),{hidden:true});assert.deepEqual(galleryTiles(12,2),{});
assert.ok(imageCard({source:'attachment',record:{id:'u9',name:'a.png',is_image:true}},'A').includes('/api/attachments/u9'));
assert.ok(!imageCard({source:'artifact',record:{id:'x',path:'a.md'}},'doc',{hidden:true}));
assert.ok(galleryMarkup(['<i></i>']).includes('data-lightbox-group'));
// Standalone images and attachments keep their original click paths out of the generic file opener.
assert.ok(!renderMarkdown('![Proof](media/shot.png)',context).includes('data-action="rich-file" data-source="artifact" data-id="a2"><img'));
console.log('Rich content gallery: 14 assertions passed');
